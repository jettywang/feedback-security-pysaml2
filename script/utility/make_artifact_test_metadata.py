import os
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TESTS_DIR = os.path.join(REPO_ROOT, "tests")
sys.path.insert(0, TESTS_DIR)

from pathutils import full_path
from pathutils import xmlsec_path

from saml2 import BINDING_HTTP_ARTIFACT
from saml2 import BINDING_HTTP_POST
from saml2 import BINDING_HTTP_REDIRECT
from saml2 import BINDING_SOAP
from saml2.config import IdPConfig
from saml2.config import SPConfig
from saml2.metadata import create_metadata_string

OUT = TESTS_DIR

IDP_EID = "urn:mace:example.com:artifact:idp"
SP1_EID = "urn:mace:example.com:artifact:sp1"
SP2_EID = "urn:mace:example.com:artifact:sp2"

IDP_BASE = "http://idp.artifact.example"
SP1_BASE = "http://sp1.artifact.example"
SP2_BASE = "http://sp2.artifact.example"


def md_conf(files):
    entries = ",\n            ".join(f'(full_path("{name}"),)' for name in files)
    return (
        "[\n"
        "            {\n"
        '                "class": "saml2.mdstore.MetaDataFile",\n'
        f'                "metadata": [\n            {entries}\n            ],\n'
        "            }\n"
        "        ]"
    )


def sp_conf_text(entityid, base, key_name, cert_name, peer_meta):
    return f'''CONFIG = {{
    "entityid": "{entityid}",
    "name": "{entityid}",
    "description": "Artifact test SP",
    "service": {{
        "sp": {{
            "endpoints": {{
                "assertion_consumer_service": [("{base}/acs", BINDING_HTTP_POST)],
                "artifact_resolution_service": [("{base}/ars", BINDING_SOAP)],
            }},
            "idp": ["{IDP_EID}"],
            "want_artifact_resolves_signed": True,
        }}
    }},
    "debug": 1,
    "key_file": full_path("{key_name}"),
    "cert_file": full_path("{cert_name}"),
    "xmlsec_binary": xmlsec_path,
    "accepted_time_diff": 60,
    "attribute_map_dir": full_path("attributemaps"),
    "artifact_ttl": 300,
    "metadata": {md_conf(peer_meta)},
}}
'''


def idp_conf_text():
    return f'''CONFIG = {{
    "entityid": "{IDP_EID}",
    "name": "Artifact test IdP",
    "service": {{
        "idp": {{
            "endpoints": {{
                "single_sign_on_service": [
                    ("{IDP_BASE}/sso/redirect", BINDING_HTTP_REDIRECT),
                    ("{IDP_BASE}/sso/art", BINDING_HTTP_ARTIFACT),
                ],
                "artifact_resolution_service": [("{IDP_BASE}/ars", BINDING_SOAP)],
            }},
            "policy": {{
                "default": {{
                    "lifetime": {{"minutes": 15}},
                    "name_form": "urn:oasis:names:tc:SAML:2.0:attrname-format:uri",
                }},
            }},
            "want_artifact_resolves_signed": True,
        }}
    }},
    "debug": 1,
    "key_file": full_path("test.key"),
    "cert_file": full_path("test.pem"),
    "xmlsec_binary": xmlsec_path,
    "accepted_time_diff": 60,
    "attribute_map_dir": full_path("attributemaps"),
    "artifact_ttl": 300,
    "metadata": {md_conf(["artifact_sp1.xml", "artifact_sp2.xml"])},
}}
'''


HEADER = '''"""Configuration for the artifact security tests.

This file is generated by script/utility/make_artifact_test_metadata.py and
is kept under version control so the tests need no generation step.
"""

from pathutils import full_path
from pathutils import xmlsec_path

from saml2 import BINDING_HTTP_ARTIFACT
from saml2 import BINDING_HTTP_POST
from saml2 import BINDING_HTTP_REDIRECT
from saml2 import BINDING_SOAP


'''


def write_conf(prefix, text):
    path = os.path.join(OUT, f"{prefix}_conf.py")
    with open(path, "w") as fd:
        fd.write(HEADER + text)
    return path


def write_meta(prefix, conf, conf_cls):
    loaded = conf_cls().load(conf)
    xml = create_metadata_string(None, config=loaded)
    path = os.path.join(OUT, f"{prefix}.xml")
    with open(path, "wb") as fd:
        fd.write(xml)
    return path


sp1_conf_text = sp_conf_text(SP1_EID, SP1_BASE, "test_1.key", "test_1.crt", ["artifact_idp.xml"])
sp2_conf_text = sp_conf_text(SP2_EID, SP2_BASE, "test_2.key", "test_2.crt", ["artifact_idp.xml"])
idp_text = idp_conf_text()

write_conf("artifact_sp1", sp1_conf_text)
write_conf("artifact_sp2", sp2_conf_text)
write_conf("artifact_idp", idp_text)

# Load the freshly written configs to emit matching metadata.
sys.path.insert(0, OUT)
import importlib

sp1_conf = importlib.import_module("artifact_sp1_conf").CONFIG
sp2_conf = importlib.import_module("artifact_sp2_conf").CONFIG
idp_conf = importlib.import_module("artifact_idp_conf").CONFIG

write_meta("artifact_sp1", sp1_conf, SPConfig)
write_meta("artifact_sp2", sp2_conf, SPConfig)
write_meta("artifact_idp", idp_conf, IdPConfig)
print("generated")
